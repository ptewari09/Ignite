import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { expect, test } from '../support/liveFixture';
import type { TransformationFinding } from '../../src/types/evidence';
import type { Page } from '../../src/types/workspace';

test('live FastAPI evidence preserves provenance and paginates synthetic workbook rows', async ({ page, request, verifiedLiveApi: api }, testInfo) => {
  test.setTimeout(90_000);
  const root = resolve('..');
  const python = process.env.TRACESYNC_TEST_PYTHON ?? resolve(root, 'backend/.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
  execFileSync(python, ['-m', 'app.scripts.generate_demo_workbooks', '--output', testInfo.outputDir], { cwd: root, stdio: 'pipe' });
  const expand = [
    'import sys', 'from pathlib import Path', 'from openpyxl import load_workbook',
    'path = Path(sys.argv[1]) / "synthetic-transformation.xlsx"', 'book = load_workbook(path)', 'sheet = book["Detailed_LOG"]',
    'for index in range(30):',
    '    sheet.append(["DEMO", "PROG", f"Z_EVIDENCE_EXTRA_{index:03}", "OBJ_LOCKED", f"Fictional pagination finding {index}.", None, None])',
    'book.save(path)', 'book.close()',
  ].join('\n');
  execFileSync(python, ['-c', expand, testInfo.outputDir], { cwd: root, stdio: 'pipe' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  const projectName = `Synthetic evidence acceptance ${Date.now()}`;
  await page.goto('/projects');
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.getByLabel('Project name', { exact: false }).fill(projectName);
  const projectResponse = page.waitForResponse((response) => response.url() === `${api}/projects` && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  const project = await (await projectResponse).json() as { id: string };
  await page.getByRole('button', { name: 'New cycle', exact: true }).click();
  await page.getByLabel('Cycle name', { exact: false }).fill('Synthetic evidence cycle');
  const cycleResponse = page.waitForResponse((response) => response.url() === `${api}/projects/${project.id}/cycles` && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create cycle', exact: true }).click();
  const cycle = await (await cycleResponse).json() as { id: string };
  const navigation = page.getByRole('navigation', { name: 'Primary navigation' });
  await navigation.getByRole('link', { name: 'Evidence Explorer', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Transformation Report not imported' })).toBeVisible();
  await page.getByRole('link', { name: 'Go to Upload Reports' }).click();
  await expect(page.getByLabel('Transformation Report workbook', { exact: true })).toBeEnabled();
  await page.getByLabel('Transformation Report workbook', { exact: true }).setInputFiles(resolve(testInfo.outputDir, 'synthetic-transformation.xlsx'));
  await page.getByRole('button', { name: 'Upload Transformation Report', exact: true }).click();
  await expect(page.getByText('Uploaded successfully', { exact: true })).toHaveCount(1);
  await page.getByLabel('Post-Upload Report workbook', { exact: true }).setInputFiles(resolve(testInfo.outputDir, 'synthetic-post-upload.xlsx'));
  await page.getByRole('button', { name: 'Upload Post-Upload Report', exact: true }).click();
  await expect(page.getByText('Uploaded successfully', { exact: true })).toHaveCount(2);
  const sourcesBefore = await (await request.get(`${api}/cycles/${cycle.id}/workbooks`)).json();
  const endpoint = `${api}/cycles/${cycle.id}/transformation-findings`;
  const firstResponse = page.waitForResponse((response) => response.url() === `${endpoint}?limit=25&offset=0`);
  await navigation.getByRole('link', { name: 'Evidence Explorer', exact: true }).click();
  const firstHttp = await firstResponse;
  expect(firstHttp.status()).toBe(200);
  const first = await firstHttp.json() as Page<TransformationFinding>;
  expect(first).toMatchObject({ total: 33, limit: 25, offset: 0 });
  expect(first.items).toHaveLength(25);
  await expect(page.getByText('Records 1–25 of 33', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Inspect Detailed_LOG row 2', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Inspect Detailed_LOG row 4', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Inspect Detailed_LOG row 2', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByText('" prog  "', { exact: true })).toBeVisible();
  await expect(dialog.getByText('PROG', { exact: true })).toBeVisible();
  await expect(dialog.getByText('Z_DEMO_ORDER', { exact: true })).toBeVisible();
  await expect(dialog.getByText(first.items[0].id, { exact: true })).toBeVisible();
  await dialog.getByText('Original row payload — all source columns', { exact: true }).click();
  expect(JSON.parse(await dialog.getByLabel('Original row payload', { exact: true }).innerText())).toEqual(first.items[0].raw_payload);
  await page.screenshot({ path: 'test-results/evidence-live-detail.png', animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.getByRole('searchbox', { name: 'Filter current page' }).fill('Z_EVIDENCE_EXTRA_029');
  await expect(page.getByRole('heading', { name: 'No matches on this page' })).toBeVisible();
  const nextResponse = page.waitForResponse((response) => response.url() === `${endpoint}?limit=25&offset=25`);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  const second = await (await nextResponse).json() as Page<TransformationFinding>;
  expect(second).toMatchObject({ total: 33, limit: 25, offset: 25 });
  expect(second.items).toHaveLength(8);
  expect(new Set([...first.items, ...second.items].map((record) => record.id)).size).toBe(33);
  await expect(page.getByText('Records 26–33 of 33', { exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Z_EVIDENCE_EXTRA_029', exact: true })).toBeVisible();
  await expect(page.getByRole('searchbox')).toHaveValue('');
  await expect(page.getByRole('button', { name: 'Next', exact: true })).toBeDisabled();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/evidence-live-desktop.png', animations: 'disabled' });
  await page.getByRole('tab', { name: 'Upload Objects', exact: true }).click();
  await expect(page.getByText('Records 1–3 of 3', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Inspect Objects row 2', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: 'Imported manual annotations' })).toBeVisible();
  await expect(dialog.getByText('"UPLD_ERROR"', { exact: true })).toBeVisible();
  await expect(dialog.getByText('"Uploaded"', { exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('tab', { name: 'Upload Errors', exact: true }).click();
  await expect(page.getByText('Records 1–4 of 4', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 320, height: 844 });
  await expect(page.getByRole('tab', { name: 'Upload Errors', exact: true })).toBeInViewport({ ratio: 1 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/evidence-live-320.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Inspect Errors row 3', exact: true }).click();
  await expect(dialog.getByText('"    "', { exact: true })).toBeVisible();
  await expect(dialog.getByText('"Fictional component context.   "', { exact: true })).toBeVisible();
  await expect(dialog.getByLabel('Not provided', { exact: true })).toHaveCount(3);
  await page.screenshot({ path: 'test-results/evidence-live-detail-320.png', animations: 'disabled' });
  await page.keyboard.press('Escape');
  const sourcesAfter = await (await request.get(`${api}/cycles/${cycle.id}/workbooks`)).json();
  expect(sourcesAfter).toEqual(sourcesBefore);
  expect((await (await request.get(`${endpoint}?limit=25&offset=0`)).json()).items).toEqual(first.items);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await navigation.getByRole('link', { name: 'Projects', exact: true }).click();
  await page.getByRole('button', { name: 'New cycle', exact: true }).click();
  await page.getByLabel('Cycle name', { exact: false }).fill('Synthetic empty evidence cycle');
  await page.getByRole('button', { name: 'Create cycle', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select cycle Synthetic empty evidence cycle', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await navigation.getByRole('link', { name: 'Evidence Explorer', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Transformation Findings', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('heading', { name: 'Transformation Report not imported' })).toBeVisible();
});
